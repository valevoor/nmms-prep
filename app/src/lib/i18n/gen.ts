export const GEN: Record<Locale, GenText> = { en: genEn, kn: genKn }

/** A sentence in every language. */
export type Text = Record<Locale, string>

/** Builds one sentence in every language: both((m) => m.addEach(5)). `l` picks from other Texts. */
export const both = (f: (m: GenText, l: Locale) => string): Text => ({ en: f(genEn, 'en'), kn: f(genKn, 'kn') })

/** Text that reads the same in every language (pure maths, e.g. "6² − 1 = 35"). */
export const same = (s: string): Text => ({ en: s, kn: s })
